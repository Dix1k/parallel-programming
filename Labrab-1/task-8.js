// --- Вспомогательные функции ---
function log(level, message) {
    console.log(`${'  '.repeat(level)}[L${level}] ${message}`);
}

// --- 1. Алгоритм Штрассена (упрощённая версия с логированием графа) ---
function strassenGraph(n, level = 0) {
    log(level, `Штрассен: n=${n}`);
    
    if (n <= 2) {
        log(level + 1, `Базовый случай: прямое умножение 2x2`);
        return;
    }
    
    // Делит матрицу на блоки и делает 7 рекурсивных вызовов
    const half = n / 2;
    for (let i = 1; i <= 7; i++) {
        log(level + 1, `Рекурсивный вызов Штрассена #${i} для размера ${half}`);
        strassenGraph(half, level + 2);
    }
}

// --- 2. Быстрое преобразование Фурье (БПФ по основанию 2) с логированием графа ---
function fftGraph(n, level = 0) {
    log(level, `БПФ: длина последовательности = ${n}`);
    
    if (n === 1) {
        log(level + 1, `Базовый случай: один элемент`);
        return;
    }
    
    const half = n / 2;
    
    // Разделение на чётные и нечётные
    log(level + 1, `Рекурсия для чётных индексов (размер ${half})`);
    fftGraph(half, level + 2);
    
    log(level + 1, `Рекурсия для нечётных индексов (размер ${half})`);
    fftGraph(half, level + 2);
    
    // Показываем "бабочку" на этом уровне
    log(level + 1, `Выполнение бабочки-операций между результатами`);
}

// === Тестирование: сравнение структур графов ===
console.log("=== ГРАФ АЛГОРИТМА ШТРАССЕНА (n=4) ===");
strassenGraph(4);

console.log("\n=== ГРАФ АЛГОРИТМА БПФ (n=8) ===");
fftGraph(8);

/*
Что делает этот код:
Моделирует структуру графа вычислений через логирование.
Для Штрассена: показывает, что на каждом уровне происходит 7 рекурсивных вызовов.
Для БПФ: показывает два вызова и регулярную структуру ("бабочка").
Позволяет сравнить ветвление и глубину — ключевые свойства графов.

Вывод
Граф Штрассена — это древовидная структура с высоким ветвлением (7), отражающая разложение матриц и рекурсивные умножения.
    Подходит для параллельных систем, но сложен в балансировке.
Граф БПФ — регулярный бабочка-граф, высоко оптимизированный,
    используется в DSP, сетях и алгоритмах типа Cooley-Tukey.

Хотя оба алгоритма делят задачу пополам, их графы принципиально отличаются:
Штрассен — дерево с множественными рекурсивными вызовами,
БПФ — циклическая сеть с фиксированными шаблонами связи.
*/